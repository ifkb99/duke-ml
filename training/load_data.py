"""
Load self-play training data generated by the TypeScript engine.

Generate data first:
  npx tsx packages/ai/src/generate.ts 100 4 selfplay.bin

Usage:
  source .venv/bin/activate
  python training/load_data.py [path_to_bin]
"""

import sys
import os
from pathlib import Path
from typing import TypedDict

import numpy as np
import jax.numpy as jnp

# ── Constants (must match packages/ai/src/encoding.ts) ──

BOARD_SIZE = 6
NUM_TILE_TYPES = 15
NUM_CHANNELS = 33
BOARD_TENSOR_SIZE = NUM_CHANNELS * BOARD_SIZE * BOARD_SIZE  # 1188
BAG_FEATURE_SIZE = NUM_TILE_TYPES * 2                       # 30
STATE_TENSOR_SIZE = BOARD_TENSOR_SIZE + BAG_FEATURE_SIZE    # 1218
TOTAL_ACTIONS = 4428
SAMPLE_FLOATS = STATE_TENSOR_SIZE + 2                       # 1220

TILE_NAMES = [
    'Duke', 'Footman', 'Priest', 'Champion', 'Assassin', 'Bowman',
    'Dragoon', 'Pikeman', 'General', 'Marshall', 'Longbowman', 'Knight',
    'Seer', 'Wizard', 'Ranger',
]


class SelfPlayData(TypedDict):
    boards: jnp.ndarray
    bags: jnp.ndarray
    actions: jnp.ndarray
    values: jnp.ndarray

def load_selfplay(path: str | Path) -> SelfPlayData:
    """Load a binary self-play file into JAX arrays.

    Returns a dict with:
        boards:  (N, 33, 6, 6)  float32 — board plane tensor
        bags:    (N, 30)         float32 — bag feature vector
        actions: (N,)            int32   — action indices [0, 4427]
        values:  (N,)            float32 — value targets (+1/-1/0)
    """
    raw = np.fromfile(path, dtype=np.float32)
    assert raw.size % SAMPLE_FLOATS == 0, (
        f'File size {raw.size} not divisible by {SAMPLE_FLOATS}'
    )
    data = raw.reshape(-1, SAMPLE_FLOATS)

    boards = jnp.array(data[:, :BOARD_TENSOR_SIZE].reshape(-1, NUM_CHANNELS, BOARD_SIZE, BOARD_SIZE))
    bags = jnp.array(data[:, BOARD_TENSOR_SIZE:STATE_TENSOR_SIZE])
    actions = jnp.array(data[:, STATE_TENSOR_SIZE].astype(np.int32))
    values = jnp.array(data[:, STATE_TENSOR_SIZE + 1])

    return {'boards': boards, 'bags': bags, 'actions': actions, 'values': values}

if __name__ == '__main__':
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), 'selfplay.bin')

    if not Path(path).exists():
        print(f'File not found: {path}')
        print('Generate data first: npx tsx packages/ai/src/generate.ts 100 4 selfplay.bin')
        sys.exit(1)

    d = load_selfplay(path)

    print(f'Loaded {path}')
    print(f'  boards:  {d['boards'].shape}  {d['boards'].dtype}')
    print(f'  bags:    {d['bags'].shape}  {d['bags'].dtype}')
    print(f'  actions: {d['actions'].shape}  {d['actions'].dtype}  range [{d['actions'].min()}, {d['actions'].max()}]')
    print(f'  values:  {d['values'].shape}  {d['values'].dtype}  mean {d['values'].mean():.3f}')
